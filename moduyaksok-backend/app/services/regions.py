def expand_broad_region(region: str) -> list[str]:
    """세부지역 없이 시/도만 입력된 region이면("서울") 그 시/도의 세부지역들을
    "시/도 세부지역" 형태로 펼쳐서 반환한다(예: ["서울 강남", "서울 홍대", ...]).
    이미 세부지역이 있는 region("경기 수원")이거나, REGIONS에 없는 시/도거나,
    세부지역 목록이 비어있는 시/도(세종 등)면 원래 값 그대로 담은 리스트 하나를
    반환한다 — 호출부(naver_local_search.search_places_for_regions)가 매 region마다
    이 함수를 불러서 결과를 이어붙이면 된다.
    """
    if len(region.split()) >= 2:
        return [region]
    districts = REGIONS.get(region)
    if not districts:
        return [region]
    return [f"{region} {district}" for district in districts]
